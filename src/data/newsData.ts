export const getArticleById = (id: string): NewsArticle | undefined => {
  return ALL_NEWS_ARTICLES.find(a => a.id === id);
};

export const getArticlesByCategory = (categoryId: string): NewsArticle[] => {
  if (categoryId === 'all') return ALL_NEWS_ARTICLES;
  return ALL_NEWS_ARTICLES.filter(a => a.category.toLowerCase() === categoryId.toLowerCase());
};

export const getFeaturedArticles = (): NewsArticle[] => {
  return ALL_NEWS_ARTICLES.filter(a => a.isFeatured);
};

export const getTrendingArticles = (): NewsArticle[] => {
  return ALL_NEWS_ARTICLES.filter(a => a.isTrending);
};
